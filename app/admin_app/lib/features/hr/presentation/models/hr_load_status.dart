/// حالة تحميل واحدة لكل أسطح الموارد البشرية.
///
/// `failure` لا يعني «صفر»: الشاشة التي تعرف أن قراءتها فشلت تعرض إعادة
/// محاولة، أما التي تخلط الفشل بالفراغ فتنشر صفرًا لم يقله أحد.
enum HrLoadStatus { initial, loading, ready, failure }

/// حالة كتابة واحدة: لا شيء حتى تُضغط، ثم قيد الإرسال، ثم مقبولة أو مرفوضة.
enum HrWriteStatus { idle, sending, done }

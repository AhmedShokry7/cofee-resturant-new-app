/// نتيجة تعديل بيانات موظف أو صورته كما ترد من القاعدة.
///
/// الحقول الثلاثة التي يرفضها `public.admin_update_staff` تحمل سببها في الرد
/// (`invalid_name` …)، والسبب يبقى هنا لا في النص: الشاشة تعرض رسالة عربية
/// مطابقة، والمستودع لا يقرر شيئًا نيابة عن الموظف.
enum StaffEditOutcome {
  success,

  /// الحساب خارج صلاحية الموظف الحالي أو لا يعرفه: `42501` من القاعدة.
  permissionDenied,

  /// محاولة تغيير حالة الحساب الذي دخل به الموظف نفسه، وهو القفل الذي يمنع
  /// تعليق المرء لنفسه بلا طريق رجوع.
  selfStatus,
  invalidName,
  invalidEmail,
  duplicateEmail,
  invalidStatus,

  /// مسار صورة ليس داخل `staff/<id>/`، وهو ما ترفضه الترحيلة 209.
  invalidPath,
  failed,
}

import 'package:new_coffee/core/locale/app_strings.dart';

/// Customer-facing text a manager holds as a token instead of a sentence.
///
/// State outlives the language it was written in: a cubit that puts `S.foo` in
/// its state stores the words the app was showing at that moment, and the
/// customer who switches language keeps reading them until the app restarts.
/// The manager stores one of these instead, and the copy is read from [S] when
/// the screen asks for it — which is the language the customer chose.
///
/// A case is named after the [S] member that says it, so a token and its copy
/// show up together in a search.
enum AppCopy {
  addressDeleteFailed,
  addressSaveFailed,
  cardDeleteFailed,
  cardSaveNotAllowed,
  couponCheckFailed,
  couponNotAppliedAtCheckout,
  cartEmpty,
  cartLineLimitReached,
  cupsRemaining,
  cartSyncFailed,
  couldNotCancelOrder,
  couldNotDeductCups,
  couldNotLoadAccountDetails,
  couldNotLoadAddresses,
  couldNotLoadCart,
  couldNotLoadOrders,
  couldNotLoadSavedCards,
  deliveryAddressRequired,
  deliveryChoosePickup,
  deliveryMinimumNotMet,
  deliveryOutOfZone,
  deliveryUnavailable,
  deliveryUnavailableError,
  deliveryZoneRequired,
  favoritesSyncFailed,
  invalidQuantity,
  orderFailed,
  passwordChangeFailed,
  profileUpdateFailed,
  productNoLongerAvailable,
  reviewSubmitFailed,
  saveCardFailed,
  selectBranchBeforePaying,
  signIn,
  signInToSeeOrders,
  productUnavailable,
  bundleLabel,
  invalidCardDetails,
  tokenizationFailed,
  paymentNotCompleted,
  paymentVerificationFailed,
  paymentRetryLater,
  cardAlreadyRemoved,
  cardDeclined,
  cardHolderRequired,
  cardSavingNotConfigured,
  invalidCvv,
  invalidDate,
  validCardNumber,
  couldNotLoadCheckout,
  couldNotLoadProduct,
  couldNotLoadFavorites,
  authEmailNotConfirmed,
  authEmailInUse,
  authFailed,
  authGoogleNoAccount,
  authGoogleRefused,
  authGoogleUnavailable,
  authInvalidCredentials,
  authInvalidEmail,
  authOtpInvalid,
  authProviderNotEnabled,
  authRecoveryLinkRequired,
  authSmsSendFailed,
  authStaffAccount,
  authTooManyRequests,
  authUnexpected,
  authUserDisabled,
  authUserNotFound,
  authWeakPassword,
  authServiceUnavailable,
  logoutFailed,
  validPhoneNumber;

  /// What the customer reads for this token, in the language they chose.
  ///
  /// [cartLineLimitReached] and [cupsRemaining] are the exceptions: each quotes
  /// a number that belongs to a feature rather than to here, so that feature's
  /// state resolves the case. Reading it from here would either hard-code the
  /// number a second time or print the wrong one.
  String get copy => switch (this) {
    AppCopy.cupsRemaining => throw UnsupportedError(
      'SubscriptionConsumeState.messageCopy resolves cupsRemaining: the count '
      'comes from the server answer, not from here.',
    ),
    AppCopy.addressDeleteFailed => S.addressDeleteFailed,
    AppCopy.couldNotLoadFavorites => S.couldNotLoadFavorites,
    AppCopy.couldNotLoadProduct => S.couldNotLoadProduct,
    AppCopy.couldNotLoadCheckout => S.couldNotLoadCheckout,
    AppCopy.validCardNumber => S.validCardNumber,
    AppCopy.invalidDate => S.invalidDate,
    AppCopy.invalidCvv => S.invalidCvv,
    AppCopy.cardSavingNotConfigured => S.cardSavingNotConfigured,
    AppCopy.cardHolderRequired => S.cardHolderRequired,
    AppCopy.cardDeclined => S.cardDeclined,
    AppCopy.cardAlreadyRemoved => S.cardAlreadyRemoved,
    AppCopy.paymentRetryLater => S.paymentRetryLater,
    AppCopy.paymentVerificationFailed => S.paymentVerificationFailed,
    AppCopy.paymentNotCompleted => S.paymentNotCompleted,
    AppCopy.tokenizationFailed => S.tokenizationFailed,
    AppCopy.invalidCardDetails => S.invalidCardDetails,
    AppCopy.bundleLabel => S.bundleLabel,
    AppCopy.productUnavailable => S.productUnavailable,
    AppCopy.addressSaveFailed => S.addressSaveFailed,
    AppCopy.cardDeleteFailed => S.cardDeleteFailed,
    AppCopy.cardSaveNotAllowed => S.cardSaveNotAllowed,
    AppCopy.couponCheckFailed => S.couponCheckFailed,
    AppCopy.couponNotAppliedAtCheckout => S.couponNotAppliedAtCheckout,
    AppCopy.cartEmpty => S.cartEmpty,
    AppCopy.cartLineLimitReached => throw UnsupportedError(
      'CartState.errorCopy resolves cartLineLimitReached: the cart owns the '
      'limit quoted in the sentence.',
    ),
    AppCopy.cartSyncFailed => S.cartSyncFailed,
    AppCopy.couldNotCancelOrder => S.couldNotCancelOrder,
    AppCopy.couldNotDeductCups => S.couldNotDeductCups,
    AppCopy.couldNotLoadAccountDetails => S.couldNotLoadAccountDetails,
    AppCopy.couldNotLoadAddresses => S.couldNotLoadAddresses,
    AppCopy.couldNotLoadCart => S.couldNotLoadCart,
    AppCopy.couldNotLoadOrders => S.couldNotLoadOrders,
    AppCopy.couldNotLoadSavedCards => S.couldNotLoadSavedCards,
    AppCopy.deliveryAddressRequired => S.deliveryAddressRequired,
    AppCopy.deliveryChoosePickup => S.deliveryChoosePickup,
    AppCopy.deliveryMinimumNotMet => S.deliveryMinimumNotMet,
    AppCopy.deliveryOutOfZone => S.deliveryOutOfZone,
    AppCopy.deliveryUnavailable => S.deliveryUnavailable,
    AppCopy.deliveryUnavailableError => S.deliveryUnavailableError,
    AppCopy.deliveryZoneRequired => S.deliveryZoneRequired,
    AppCopy.favoritesSyncFailed => S.favoritesSyncFailed,
    AppCopy.invalidQuantity => S.invalidQuantity,
    AppCopy.orderFailed => S.orderFailed,
    AppCopy.passwordChangeFailed => S.passwordChangeFailed,
    AppCopy.profileUpdateFailed => S.profileUpdateFailed,
    AppCopy.productNoLongerAvailable => S.productNoLongerAvailable,
    AppCopy.reviewSubmitFailed => S.reviewSubmitFailed,
    AppCopy.saveCardFailed => S.saveCardFailed,
    AppCopy.selectBranchBeforePaying => S.selectBranchBeforePaying,
    AppCopy.signIn => S.signIn,
    AppCopy.signInToSeeOrders => S.signInToSeeOrders,
    AppCopy.validPhoneNumber => S.validPhoneNumber,
    AppCopy.authEmailNotConfirmed => S.authEmailNotConfirmed,
    AppCopy.authEmailInUse => S.authEmailInUse,
    AppCopy.authFailed => S.authFailed,
    AppCopy.authGoogleNoAccount => S.authGoogleNoAccount,
    AppCopy.authGoogleRefused => S.authGoogleRefused,
    AppCopy.authGoogleUnavailable => S.authGoogleUnavailable,
    AppCopy.authInvalidCredentials => S.authInvalidCredentials,
    AppCopy.authInvalidEmail => S.authInvalidEmail,
    AppCopy.authOtpInvalid => S.authOtpInvalid,
    AppCopy.authProviderNotEnabled => S.authProviderNotEnabled,
    AppCopy.authRecoveryLinkRequired => S.authRecoveryLinkRequired,
    AppCopy.authSmsSendFailed => S.authSmsSendFailed,
    AppCopy.authStaffAccount => S.authStaffAccount,
    AppCopy.authTooManyRequests => S.authTooManyRequests,
    AppCopy.authUnexpected => S.authUnexpected,
    AppCopy.authUserDisabled => S.authUserDisabled,
    AppCopy.authUserNotFound => S.authUserNotFound,
    AppCopy.authWeakPassword => S.authWeakPassword,
    AppCopy.authServiceUnavailable => S.authServiceUnavailable,
    AppCopy.logoutFailed => S.logoutFailed,
  };
}
